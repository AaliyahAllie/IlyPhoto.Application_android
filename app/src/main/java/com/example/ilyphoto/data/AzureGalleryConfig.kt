package com.example.ilyphoto.data

import android.net.Uri

/**
 * Public, non-secret Azure gallery settings.
 *
 * The storage account key must stay on a trusted backend. For private galleries,
 * the backend should authorize the signed-in client and return short-lived SAS URLs.
 */
object AzureGalleryConfig {
    const val ACCOUNT_NAME = "ilyphotostorage"
    const val CONTAINER_NAME = "ilyphoto-galleries"

    val containerUrl: String
        get() = "https://$ACCOUNT_NAME.blob.core.windows.net/$CONTAINER_NAME"

    /**
     * Builds a blob URL only for public blobs. For private blobs, use the SAS URL
     * returned by the backend instead; do not append an account key in the app.
     */
    fun publicBlobUrl(blobName: String): String {
        require(blobName.isNotBlank()) { "Blob name cannot be blank." }
        val encodedPath = blobName.split("/")
            .joinToString("/") { Uri.encode(it) }
        return "$containerUrl/$encodedPath"
    }

    /**
     * Gallery metadata can store either a full URL (preferably a short-lived SAS URL
     * supplied by the backend) or a relative blob path in storagePath.
     */
    fun resolveImageUrl(imageUrl: String, storagePath: String): String? {
        val existingUrl = imageUrl.trim()
        if (existingUrl.startsWith("https://", ignoreCase = true)) return existingUrl

        val blobPath = storagePath.trim()
        if (blobPath.isEmpty()) return null

        // Relative paths are only directly usable if the container permits public reads.
        // Private containers must use a SAS URL generated by the backend.
        return publicBlobUrl(blobPath)
    }
}
